// Generates src/css/nothing-icons.css: the Nothing interface style draws
// every icon from Flaticon's thin-lined "regular rounded" set instead of the
// default "bold rounded" one. The app's markup only ever uses fi-br-* class
// names, so this maps each one it uses to the regular set's glyph.
//
// Run after adding or changing an icon:  node scripts/nothing-icons.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const PKG = path.join(ROOT, 'node_modules', '@flaticon', 'flaticon-uicons', 'css');
const FONT = 'uicons-regular-rounded-J3WOUERV.woff2';

function glyphs(file, prefix) {
  const css = fs.readFileSync(path.join(PKG, file), 'utf8');
  const map = {};
  const re = new RegExp(`\\.${prefix}-([a-z0-9-]+):before\\{content:"\\\\([0-9a-f]+)"\\}`, 'g');
  for (const [, name, code] of css.matchAll(re)) map[name] = code;
  return map;
}

function sourceFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return ['vendor', 'locales', 'themes'].includes(entry.name) ? [] : sourceFiles(full);
    return /\.(html|js)$/.test(entry.name) ? [full] : [];
  });
}

const used = new Set();
for (const file of sourceFiles(SRC)) {
  for (const [, name] of fs.readFileSync(file, 'utf8').matchAll(/fi-br-([a-z0-9-]+)/g)) used.add(name);
}

const regular = glyphs('regular/rounded.css', 'fi-rr');
const rules = [];
const missing = [];
for (const name of [...used].sort()) {
  if (regular[name]) rules.push(`:root[data-ui="nothing"] .fi-br-${name}:before { font-family: uicons-regular-rounded !important; content: "\\${regular[name]}"; }`);
  else missing.push(name);
}

fs.copyFileSync(path.join(PKG, FONT), path.join(SRC, 'vendor', 'uicons', FONT));
fs.writeFileSync(path.join(SRC, 'css', 'nothing-icons.css'), `/* Generated by scripts/nothing-icons.js -- don't edit by hand.
   Nothing style: thin-lined icons (Flaticon uicons "regular rounded") in
   place of the default bold ones. The font only downloads when this style
   is on, since nothing else references it. */
@font-face {
  font-family: uicons-regular-rounded;
  src: url(../vendor/uicons/${FONT}) format("woff2");
  font-display: block;
}
${rules.join('\n')}
`);
console.log(`${rules.length} icons mapped` + (missing.length ? `; kept bold (no regular version): ${missing.join(', ')}` : ''));
